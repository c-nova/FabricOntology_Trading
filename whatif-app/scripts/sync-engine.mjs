// whatif-engine/src を、Functions のパッケージ内にコピーする（デプロイは「ソースのみの zip」で、
// フォルダ外への file: 依存が使えないため）。正は whatif-engine/src。コピー側は手で編集しない。
//
//   node scripts/sync-engine.mjs          コピーする
//   node scripts/sync-engine.mjs --check  差分があれば終了コード 1（コミット前・CI 用）
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const source = path.resolve(root, '..', 'whatif-engine', 'src');
const target = path.resolve(root, 'packages', 'functions', 'src', 'engine');
// ローカルデータ読み込み用で、Functions では使わない
const EXCLUDE = new Set(['local-loader.ts']);
const BANNER =
  '// GENERATED by scripts/sync-engine.mjs from whatif-engine/src. Do not edit here; edit the source and re-run.\n';

const files = (dir) => readdirSync(dir).filter((f) => f.endsWith('.ts') && !EXCLUDE.has(f)).sort();
const withBanner = (text) => BANNER + text;

function expected() {
  const map = new Map();
  for (const f of files(source)) map.set(f, withBanner(readFileSync(path.join(source, f), 'utf8')));
  return map;
}

const digest = (s) => createHash('sha256').update(s).digest('hex').slice(0, 12);

if (!existsSync(source)) {
  console.error(`engine source not found: ${source}`);
  process.exit(2);
}

const want = expected();

if (process.argv.includes('--check')) {
  const have = existsSync(target) ? new Set(readdirSync(target).filter((f) => f.endsWith('.ts'))) : new Set();
  const problems = [];
  for (const [f, text] of want) {
    if (!have.has(f)) problems.push(`missing  ${f}`);
    else if (readFileSync(path.join(target, f), 'utf8') !== text) problems.push(`differs  ${f}`);
  }
  for (const f of have) if (!want.has(f)) problems.push(`extra    ${f}`);
  if (problems.length) {
    console.error('engine copy is out of sync:\n  ' + problems.join('\n  ') + '\nrun: node scripts/sync-engine.mjs');
    process.exit(1);
  }
  console.log(`engine copy in sync (${want.size} files)`);
  process.exit(0);
}

rmSync(target, { recursive: true, force: true });
mkdirSync(target, { recursive: true });
for (const [f, text] of want) writeFileSync(path.join(target, f), text);
console.log(`synced ${want.size} files -> ${path.relative(root, target)}`);
for (const [f, text] of want) console.log(`  ${f}  ${digest(text)}`);
